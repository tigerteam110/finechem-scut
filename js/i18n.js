class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('fine_chem_team_lang') || localStorage.getItem('tiger_team_lang') || 'zh';
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  setLanguage(lang) {
    this.currentLang = (lang === 'en') ? 'en' : 'zh';
    localStorage.setItem('fine_chem_team_lang', this.currentLang);
    this.applyLanguage(this.currentLang);
    if (window.safetyEngine) {
      window.safetyEngine.setLanguage(this.currentLang);
    }
  }

  applyLanguage(lang) {
    const dict = I18N_RESOURCES[lang] || I18N_RESOURCES.zh;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Update switcher UI state
    const btnZh = document.getElementById('langBtnZh');
    const btnEn = document.getElementById('langBtnEn');
    if (btnZh && btnEn) {
      if (lang === 'zh') {
        btnZh.classList.add('active');
        btnEn.classList.remove('active');
      } else {
        btnZh.classList.remove('active');
        btnEn.classList.add('active');
      }
    }
    document.documentElement.lang = lang;
  }
}

window.i18n = new I18nEngine();
